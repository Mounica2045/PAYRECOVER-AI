// Helper to generate downloadable CSV file content
export const exportPaymentsToCSV = (dataList) => {
  const headers = [
    "Transaction ID",
    "Customer Name",
    "Email",
    "Amount",
    "Currency",
    "Payment Method",
    "Status",
    "Failure Reason",
    "AI Recovery Probability",
    "Recovery Status",
    "Date"
  ];

  const rows = dataList.map(item => [
    item.id,
    `"${item.customer}"`,
    item.email,
    item.amount,
    item.currency,
    item.method,
    item.status,
    `"${item.failureReason}"`,
    item.probability ? `${item.probability}%` : "N/A",
    item.recoveryStatus,
    `"${item.date}"`
  ]);

  const csvContent = [headers.join(","), ...rows.map(e => e.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", `payrecover_payments_${new Date().toISOString().slice(0, 10)}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
};
